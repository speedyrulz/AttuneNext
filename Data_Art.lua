-- Apply an art-pack sprite to a Texture. Returns true when applied.
function ANx.SetArt(tex, key)
    local a = ANx.Art and ANx.Art[key]
    if not (a and tex and tex.SetTexture) then return false end
    tex:SetTexture(ANx.ART_PATH .. a[1])
    if tex.SetTexCoord then tex:SetTexCoord(a[2], a[4], a[3], a[5]) end
    return true
end

-- Reset a Texture back to plain full-image mode (for reused row icons).
